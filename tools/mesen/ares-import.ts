// Turns an ares savestate of Mr. Nutz into a Mesen Lua prelude that transplants its WRAM, VRAM and CGRAM into a
// Mesen state of the same scene (research tool; the ares file is only read).
// CLI: tsx tools/mesen/ares-import.ts <file.bsN> <name>   -> output/ares/<name>.lua (private: the user's game state)
// Use: tsx tools/mesen/run.ts <script.lua> --state output/states/stage-NN.mss --prelude output/ares/<name>.lua
// The prelude copies the three memories once, at the main-loop wait ($00:822E-$8233) of the first frames after the
// state load, so the stack depth matches. OAM is not copied: the game uploads its OAM buffer every NMI. PPU registers
// come from the Mesen state, so it must be the same stage/area.
// Offsets (ares v148, 268001-byte states): WRAM 0xA8C, VRAM 0x20C28, CGRAM 0x311DB. 265953-byte states (older ares
// saves) keep WRAM at 0x28C; their VRAM/CGRAM offsets were not checked, so those are refused.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LAYOUTS: Record<number, { wram: number; vram: number; cgram: number }> = {
  268001: { wram: 0xa8c, vram: 0x20c28, cgram: 0x311db },
};

export function aresPrelude(state: Buffer): { lua: string; info: Record<string, string | number> } {
  const l = LAYOUTS[state.length];
  if (!l) throw new Error(`unsupported ares state size ${state.length}`);
  const wram = state.subarray(l.wram, l.wram + 0x20000);
  const vram = state.subarray(l.vram, l.vram + 0x10000);
  const cgram = state.subarray(l.cgram, l.cgram + 0x200);
  if (wram.readUInt16LE(0x1be00) !== 0x5a4e) throw new Error("WRAM check failed: no mod magic at $7F:BE00");
  const w16 = (a: number) => wram.readUInt16LE(a);
  const info = {
    stage: wram[0x054c], scene: ((wram[0x0560] << 16) | w16(0x055e)).toString(16), x: w16(0x37), y: w16(0x39),
    fur: wram[0x1be02], outfit: wram[0x1be03],
  };
  const hex = (b: Buffer) => b.toString("hex").toUpperCase();
  const lua = `-- ares transplant (generated by tools/mesen/ares-import.ts; private)
local AR_W, AR_V, AR_C = "${hex(wram)}", "${hex(vram)}", "${hex(cgram)}"
ARES_DONE = false
local function arCopy(s, mem) for i = 0, #s / 2 - 1 do emu.write(i, tonumber(s:sub(i * 2 + 1, i * 2 + 2), 16), mem) end end
local function arDo()
  if ARES_DONE or FRAME < 2 then return end
  ARES_DONE = true
  arCopy(AR_W, emu.memType.snesWorkRam); arCopy(AR_V, emu.memType.snesVideoRam); arCopy(AR_C, emu.memType.snesCgRam)
  ARES_FRAME = FRAME
  print("ARES transplant at F" .. FRAME)
end
for _, bank in ipairs({ 0x00, 0x80 }) do
  emu.addMemoryCallback(arDo, emu.callbackType.exec, bank * 0x10000 + 0x822E, bank * 0x10000 + 0x8233, emu.cpuType.snes, emu.memType.snesMemory)
end
`;
  return { lua, info };
}

if (process.argv[1]?.endsWith("ares-import.ts")) {
  const [file, name] = process.argv.slice(2);
  if (!file || !name) throw new Error("usage: tsx tools/mesen/ares-import.ts <file.bsN> <name>");
  const { lua, info } = aresPrelude(readFileSync(file));
  mkdirSync(join("output", "ares"), { recursive: true });
  const out = join("output", "ares", `${name}.lua`);
  writeFileSync(out, lua);
  console.log(`${out}`, JSON.stringify(info));
}
